def _ensure_lang() -> None:
    if "lang" not in st.session_state:
        st.session_state["lang"] = "pt"


def get_lang() -> str:
    _ensure_lang()
    return st.session_state.get("lang", "pt")


def language_selector() -> str:
    _ensure_lang()
    options = ["Portugues", "English"]
    current = "Portugues" if st.session_state["lang"] == "pt" else "English"
    choice = st.sidebar.selectbox(STRINGS["pt"]["language_label"], options, index=options.index(current))
    st.session_state["lang"] = "pt" if choice == "Portugues" else "en"
    return st.session_state["lang"]


def t(key: str) -> str:
    lang = get_lang()
    strings = STRINGS.get(lang) or STRINGS.get("pt") or STRINGS.get("en") or {}
    if key in strings:
        return strings[key]
    pt_value = STRINGS.get("pt", {}).get(key)
    if pt_value is not None:
        return pt_value
    en_value = STRINGS.get("en", {}).get(key)
    if en_value is not None:
        return en_value
    return key
